#!/usr/bin/env python3
"""Generates crates/server/src/settings_defaults.rs from GameConfigWriter.java.

The Java server inserts every default that is missing from the `settings` table at startup; the
Rust server does the same with this table. Values computed at runtime in Java are mapped to
`Value::Today*` variants; any other non-literal value stops the generator so it gets a look.

Usage: python3 tools/gen_settings_defaults.py
"""
import os
import re
import shutil
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
# The Java Havana checkout: HAVANA_DIR, by default a sibling named aeyra-havana.
ROOT = Path(os.environ.get("HAVANA_DIR", HERE.parent / "aeyra-havana"))
SRC = ROOT / "Havana-Server/src/main/java/org/alexdev/havana/util/config/writer/GameConfigWriter.java"
OUT = HERE / "crates/server/src/settings_defaults.rs"

SPECIAL = {
    'String.valueOf(Integer.MAX_VALUE)': 'Text("2147483647")',
    'DateUtil.getCurrentDate("dd-MM")': "TodayDayMonth",
    "DateUtil.getCurrentDate(DateUtil.SHORT_DATE)": "Today",
}


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    rows = []
    # Block comments hold defaults Java no longer writes.
    source = re.sub(r"/\*.*?\*/", "", SRC.read_text(encoding="utf-8"), flags=re.S)
    for line in source.splitlines():
        code = line.strip()
        if code.startswith("//") or "config.put(" not in code:
            continue
        m = re.match(r'config\.put\("([^"]+)",\s*"((?:[^"\\]|\\.)*)"\);', code)
        if m:
            value = m.group(2).encode().decode("unicode_escape")
            rows.append((m.group(1), f"Text({rust_str(value)})"))
            continue
        m = re.match(r'config\.put\("([^"]+)",\s*(.+)\);', code)
        if m and m.group(2) in SPECIAL:
            rows.append((m.group(1), SPECIAL[m.group(2)]))
            continue
        if '"groups.ids.permission."' in code:
            continue  # one empty key per staff command; added when commands are ported
        raise SystemExit(f"unhandled default: {code}")

    body = "\n".join(f"    ({rust_str(k)}, {v})," for k, v in rows)
    OUT.write_text(
        "//! Defaults the server writes into `settings` when a key is missing (Java: `GameConfigWriter`).\n"
        "//! Generated by `tools/gen_settings_defaults.py`; do not edit by hand.\n"
        "//! Not generated yet: one empty `groups.ids.permission.<command>` key per staff command.\n\n"
        "#[derive(Clone, Copy, Debug)]\n"
        "pub enum Value {\n"
        "    Text(&'static str),\n"
        "    /// Today as `dd-MM`.\n"
        "    TodayDayMonth,\n"
        "    /// Today as `dd-MM-yyyy`.\n"
        "    Today,\n"
        "}\n\n"
        "use Value::*;\n\n"
        f"pub const DEFAULTS: &[(&str, Value)] = &[\n{body}\n];\n",
        encoding="utf-8",
    )
    if shutil.which("rustfmt"):
        subprocess.run(["rustfmt", "--edition", "2024", str(OUT)], check=True)
    print(f"{OUT.relative_to(HERE)}: {len(rows)} defaults")


if __name__ == "__main__":
    main()
