#!/usr/bin/env python3
"""Generates crates/server/src/web/routes_table.rs from Havana-Web's Routes.java.

The table keeps Java's route patterns and handler names, so the router can match exactly like
duckHTTPD's RouteManager (including which wildcard route wins). Run it again when Routes.java
changes:  HAVANA_DIR=~/aeyra-havana python3 tools/gen_web_routes.py
"""
import os
import re
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
ROOT = Path(os.environ.get("HAVANA_DIR", HERE.parent / "aeyra-havana"))
SRC = ROOT / "Havana-Web/src/main/java/org/alexdev/http/Routes.java"
OUT = HERE / "crates/server/src/web/routes_table.rs"

text = SRC.read_text(encoding="utf-8")
# Drop comments.
# (Only block comments that open a line: route patterns contain "/*".)
text = re.sub(r"(?m)^\s*/\*.*?\*/", "", text, flags=re.S)
text = "\n".join(l for l in text.splitlines() if not l.strip().startswith("//"))

hk = re.search(r'HOUSEKEEPING_PATH = "([^"]*)"', text).group(1)
routes = []
for m in re.finditer(r'addRoute\((\{[^}]*\}|new String\[\]\s*\{[^}]*\}|"[^"]*"|"/"\s*\+\s*HOUSEKEEPING_PATH\s*\+\s*"[^"]*"|"/"\s*\+\s*HOUSEKEEPING_PATH)\s*,\s*([A-Za-z]+::[A-Za-z_]+|new BaseController\(\))', text):
    arg, handler = m.group(1), m.group(2)
    if handler.startswith("new BaseController"):
        continue
    if "HOUSEKEEPING_PATH" in arg:
        tail = re.search(r'HOUSEKEEPING_PATH\s*(?:\+\s*"([^"]*)")?', arg).group(1) or ""
        paths = ["/" + hk + tail]
    else:
        paths = re.findall(r'"([^"]*)"', arg)
    for p in paths:
        routes.append((p, handler))

lines = [
    "// @generated by tools/gen_web_routes.py from Havana-Web's Routes.java: do not edit.",
    "",
    "/// Havana-Web's routes (pattern, `Controller::method`), in registration order.",
    "pub const ROUTES: &[(&str, &str)] = &[",
]
for p, h in routes:
    lines.append(f'    ("{p}", "{h}"),')
lines.append("];")
lines.append("")
lines.append(f'/// Java: `Routes.HOUSEKEEPING_PATH`.')
lines.append(f'pub const HOUSEKEEPING_PATH: &str = "{hk}";')
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{len(routes)} routes -> {OUT}")
