#!/usr/bin/env python3
"""Generates crates/protocol/src/ids.rs (message id <-> name tables) from the Java sources.

Client -> server ids come from registerEvent(...) calls in MessageHandler.java; server -> client ids
from the getHeader() of each class under messages/outgoing. Composers whose header is computed at
runtime are listed in a comment instead.

Usage: python3 tools/gen_message_ids.py   (run from anywhere; rewrites ids.rs)
"""
import os
import re
import shutil
import subprocess
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
# The Java Havana checkout: HAVANA_DIR, by default a sibling named aeyra-havana.
ROOT = Path(os.environ.get("HAVANA_DIR", HERE.parent / "aeyra-havana"))
MESSAGES = ROOT / "Havana-Server/src/main/java/org/alexdev/havana/messages"
OUT = HERE / "crates/protocol/src/ids.rs"
# Names for the handlers MessageHandler registers as lambdas (after what they do).
LAMBDAS = {230: "GET_GROUP_BADGES", 231: "GET_GROUP_INFO"}


def client_ids():
    ids = defaultdict(list)
    for line in (MESSAGES / "MessageHandler.java").read_text(encoding="utf-8").splitlines():
        code = line.split("//", 1)[0]
        m = re.search(r"registerEvent\((\d+),\s*new\s+(\w+)\(", code)
        if m:
            ids[int(m.group(1))].append(m.group(2))
            continue
        m = re.search(r"registerEvent\((\d+),\s*\(", code)
        if m:
            ids[int(m.group(1))].append(LAMBDAS.get(int(m.group(1)), "<lambda>"))
    return ids


def server_ids():
    ids, dynamic = defaultdict(list), []
    for path in sorted((MESSAGES / "outgoing").rglob("*.java")):
        src = path.read_text(encoding="utf-8")
        m = re.search(r"getHeader\(\)\s*\{\s*return\s+(?:\(short\)\s*)?(\d+)\s*;", src)
        if m:
            ids[int(m.group(1))].append(path.stem)
        elif "getHeader()" in src:
            # Header picked at runtime, often from an enum like CHAT (24) in the same file.
            consts = re.findall(r"^\s*([A-Z_]+)\s*\((\d+)\)\s*[,;]", src, re.M)
            for const, num in consts:
                ids[int(num)].append(f"{path.stem}.{const}")
            if not consts:
                dynamic.append(path.stem)
    return ids, dynamic


def table(name, ids):
    rows = "\n".join(f'    ({i}, "{"/".join(dict.fromkeys(n))}"),' for i, n in sorted(ids.items()))
    return f"pub const {name}: &[(u16, &str)] = &[\n{rows}\n];\n"


def main():
    client = client_ids()
    server, dynamic = server_ids()
    OUT.write_text(
        "//! Message ids and the Java class names that handle or compose them.\n"
        "//! Generated by `tools/gen_message_ids.py`; do not edit by hand.\n"
        "//! Names joined with `/` share one id.\n\n"
        f"// Composers whose header is computed at runtime: {', '.join(dynamic) or 'none'}.\n"
        + table("CLIENT", client) + "\n" + table("SERVER", server) + """
fn lookup(table: &[(u16, &'static str)], id: u16) -> Option<&'static str> {
    table.binary_search_by_key(&id, |&(i, _)| i).ok().map(|i| table[i].1)
}

/// Name of a client -> server message id.
pub fn client_name(id: u16) -> Option<&'static str> {
    lookup(CLIENT, id)
}

/// Name of a server -> client message id.
pub fn server_name(id: u16) -> Option<&'static str> {
    lookup(SERVER, id)
}

/// Lowest client -> server id handled by `name` (e.g. `"SSO"` -> 204).
pub fn client_id(name: &str) -> Option<u16> {
    CLIENT.iter().find(|(_, n)| n.split('/').any(|x| x == name)).map(|&(i, _)| i)
}

/// Lowest server -> client id composed by `name`.
pub fn server_id(name: &str) -> Option<u16> {
    SERVER.iter().find(|(_, n)| n.split('/').any(|x| x == name)).map(|&(i, _)| i)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_are_sorted_for_binary_search() {
        assert!(CLIENT.windows(2).all(|w| w[0].0 < w[1].0));
        assert!(SERVER.windows(2).all(|w| w[0].0 < w[1].0));
    }

    #[test]
    fn known_ids() {
        assert_eq!(client_id("INIT_CRYPTO"), Some(206));
        assert_eq!(client_id("SSO"), Some(204));
        assert_eq!(server_name(0), Some("HELLO"));
    }
}
""",
        encoding="utf-8",
    )
    if shutil.which("rustfmt"):
        subprocess.run(["rustfmt", "--edition", "2024", str(OUT)], check=True)
    print(f"{OUT.relative_to(ROOT)}: {len(client)} client ids, {len(server)} server ids, {len(dynamic)} dynamic")


if __name__ == "__main__":
    main()
